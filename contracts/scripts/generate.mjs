// Generates typed models from the JSON Schemas:
//   generated/ts/contracts.ts           (json-schema-to-typescript)
//   generated/swift/Contracts.swift     (quicktype, Codable structs)   → iOS companion
//   generated/kotlin/Contracts.kt       (quicktype, kotlinx.serialization) → Android companion
//   generated/python/contracts.py       (quicktype, dataclasses)       → Python backend
//
// Validation-only rules (if/then, not, contains, the x_ extension slot, overlay
// schemas) are stripped first: they constrain values, not shapes, and confuse
// code generators. The schemas, not the generated code, remain the source of truth.
import { readFileSync, writeFileSync, mkdirSync, rmSync, readdirSync, statSync } from "node:fs";
import { join, relative, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";
import { compile } from "json-schema-to-typescript";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "schemas", "v1");
const BUILD = join(ROOT, ".build", "schemas", "v1");
const OUT = join(ROOT, "generated");

// Overlays only tighten other schemas; their types are the base types.
const OVERLAYS = new Set(["finance/finance_tool_result.schema.json", "finance/finance_manifest.schema.json"]);
const VALIDATION_ONLY = new Set(["if", "then", "else", "not", "contains", "$comment", "$id", "$schema"]);

const walk = (dir) =>
  readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : p.endsWith(".json") ? [p] : [];
  });
const rel = (p) => relative(SRC, p).split("\\").join("/");

function strip(node) {
  if (Array.isArray(node)) return node.map(strip);
  if (!node || typeof node !== "object") return node;
  const out = {};
  for (const [k, v] of Object.entries(node)) {
    if (VALIDATION_ONLY.has(k)) continue;
    if (k === "patternProperties") {
      const kept = Object.fromEntries(Object.entries(v).filter(([p]) => p !== "^x_"));
      if (Object.keys(kept).length) out[k] = strip(kept);
      continue;
    }
    if (k === "allOf") {
      const kept = v.filter((s) => !(s.$ref || "").endsWith("ConfirmationPolicyRules") && Object.keys(strip(s)).length);
      if (kept.length) out[k] = strip(kept);
      continue;
    }
    out[k] = strip(v);
  }
  if (out.definitions) delete out.definitions.ConfirmationPolicyRules;
  // Map-like objects (e.g. LText: locale → text) become plain string maps;
  // quicktype silently drops patternProperties otherwise.
  if (out.patternProperties && !out.properties) {
    const values = Object.values(out.patternProperties);
    if (values.length === 1) {
      out.additionalProperties = values[0];
      delete out.patternProperties;
      delete out.minProperties;
    }
  }
  return out;
}

// 1. Write stripped copies.
rmSync(join(ROOT, ".build"), { recursive: true, force: true });
const files = walk(SRC).filter((f) => !OVERLAYS.has(rel(f)));
const bundleProps = {};
for (const file of files) {
  const r = rel(file);
  const schema = JSON.parse(readFileSync(file, "utf8"));
  mkdirSync(dirname(join(BUILD, r)), { recursive: true });
  writeFileSync(join(BUILD, r), JSON.stringify(strip(schema), null, 2));
  if (schema.definitions && !schema.properties && !schema.oneOf) {
    for (const name of Object.keys(schema.definitions)) {
      if (name !== "ConfirmationPolicyRules") bundleProps[name] = { $ref: `${r}#/definitions/${name}` };
    }
  } else {
    bundleProps[schema.title] = { $ref: r };
  }
}

// 2. One bundle schema so every type is emitted exactly once.
const bundlePath = join(BUILD, "_bundle.schema.json");
writeFileSync(
  bundlePath,
  JSON.stringify({ title: "ContractsIndex", type: "object", properties: bundleProps, additionalProperties: false }, null, 2)
);

const banner = (lang) =>
  `// GENERATED by contracts/scripts/generate.mjs from schemas/v1. Do not edit by hand.\n` +
  `// Shapes only: validate messages against the JSON Schemas for policy rules.\n`;

// 3. TypeScript.
mkdirSync(join(OUT, "ts"), { recursive: true });
const ts = await compile(JSON.parse(readFileSync(bundlePath, "utf8")), "ContractsIndex", {
  cwd: BUILD,
  bannerComment: banner("ts"),
  additionalProperties: false,
  unreachableDefinitions: false,
  strictIndexSignatures: true,
  maxItems: -1,
});
writeFileSync(join(OUT, "ts", "contracts.ts"), ts);
console.log("✓ generated/ts/contracts.ts");

// 4. Swift, Kotlin, Python via quicktype.
const quicktype = join(ROOT, "node_modules", ".bin", process.platform === "win32" ? "quicktype.cmd" : "quicktype");
const targets = [
  ["swift", "swift/Contracts.swift", ["--struct-or-class", "struct", "--access-level", "public"]],
  ["kotlin", "kotlin/Contracts.kt", ["--framework", "kotlinx", "--package", "platform.contracts"]],
  ["python", "python/contracts.py", ["--python-version", "3.7"]],
];
for (const [lang, out, extra] of targets) {
  mkdirSync(dirname(join(OUT, out)), { recursive: true });
  try {
    execFileSync(
      quicktype,
      ["--src-lang", "schema", "--lang", lang, "--top-level", "ContractsIndex", "--out", join(OUT, out), ...extra, bundlePath],
      { stdio: ["ignore", "ignore", "pipe"] }
    );
    console.log(`✓ generated/${out}`);
  } catch (e) {
    console.error(`✗ ${lang}: ${e.stderr?.toString() || e.message}`);
    process.exitCode = 1;
  }
}
